func genSwift(s *Snippet) string {
	var b strings.Builder
	b.WriteString("// Code generated by rAPI.\n")
	b.WriteString(swiftComment(s))
	b.WriteString("import Foundation\n\n")
	b.WriteString("let url = URL(string: " + swiftStr(effectiveURL(s)) + ")!\n")
	b.WriteString("var request = URLRequest(url: url)\n")
	b.WriteString("request.httpMethod = " + swiftStr(s.Method) + "\n")
	for _, h := range s.Headers {
		b.WriteString("request.setValue(" + swiftStr(h.Value) + ", forHTTPHeaderField: " + swiftStr(h.Name) + ")\n")
	}
	if s.Body != "" {
		b.WriteString("request.httpBody = " + swiftStr(s.Body) + ".data(using: .utf8)\n")
	} else if len(s.Form) > 0 {
		parts := make([]string, 0, len(s.Form))
		for _, f := range s.Form {
			parts = append(parts, f.Name+"="+f.Value)
		}
		b.WriteString("request.httpBody = " + swiftStr(strings.Join(parts, "&")) + ".data(using: .utf8)\n")
	}
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("request.timeoutInterval = %d\n", s.Timeout))
	}
	b.WriteString("\n")
	b.WriteString("let task = URLSession.shared.dataTask(with: request) { data, response, error in\n")
	b.WriteString("    if let error = error { print(error); return }\n")
	b.WriteString("    print((response as! HTTPURLResponse).statusCode)\n")
	b.WriteString("    if let data = data, let body = String(data: data, encoding: .utf8) { print(body) }\n")
	b.WriteString("}\n")
	b.WriteString("task.resume()\n")
	return b.String()
}
