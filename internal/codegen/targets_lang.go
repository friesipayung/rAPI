func genCSharp(s *Snippet) string {
	var b strings.Builder
	b.WriteString("// Code generated by rAPI.\n")
	b.WriteString(csComment(s))
	b.WriteString("using System;\nusing System.Collections.Generic;\nusing System.Net.Http;\nusing System.Text;\nusing System.Threading.Tasks;\n\n")
	b.WriteString("class Program {\n")
	b.WriteString("  static async Task Main() {\n")
	b.WriteString("    using var client = new HttpClient();\n")
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("    client.Timeout = TimeSpan.FromSeconds(%d);\n", s.Timeout))
	}
	if s.Body != "" {
		b.WriteString("    var content = new StringContent(" + csStr(s.Body) + ", Encoding.UTF8);\n")
	} else if len(s.Form) > 0 {
		b.WriteString("    var content = new FormUrlEncodedContent(new Dictionary<string, string> {\n")
		for _, f := range s.Form {
			b.WriteString("      { " + csStr(f.Name) + ", " + csStr(f.Value) + " },\n")
		}
		b.WriteString("    });\n")
	} else {
		b.WriteString("    var content = new StringContent(string.Empty);\n")
	}
	for _, h := range s.Headers {
		if strings.EqualFold(h.Name, "content-type") {
			continue // set via StringContent mediaType below
		}
		b.WriteString("    client.DefaultRequestHeaders.TryAddWithoutValidation(" + csStr(h.Name) + ", " + csStr(h.Value) + ");\n")
	}
	if ct := findHeader(s.Headers, "Content-Type"); ct != "" && s.Body != "" {
		b.WriteString("    content.Headers.ContentType = new System.Net.Http.Headers.MediaTypeHeaderValue(" + csStr(ct) + ");\n")
	}
	b.WriteString("    var request = new HttpRequestMessage(new HttpMethod(" + csStr(s.Method) + "), " + csStr(effectiveURL(s)) + ") { Content = content };\n")
	b.WriteString("    var response = await client.SendAsync(request);\n")
	b.WriteString("    var body = await response.Content.ReadAsStringAsync();\n")
	b.WriteString("    Console.WriteLine((int)response.StatusCode);\n")
	b.WriteString("    Console.WriteLine(body);\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

func findHeader(hs []model.KV, name string) string {
	for _, h := range hs {
		if strings.EqualFold(h.Name, name) {
			return h.Value
		}
	}
	return ""
}

