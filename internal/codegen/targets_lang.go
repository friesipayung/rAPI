func genRuby(s *Snippet) string {
	var b strings.Builder
	b.WriteString("# Code generated by rAPI.\n")
	b.WriteString(rubyComment(s))
	b.WriteString("require 'net/http'\nrequire 'uri'\n\n")
	b.WriteString("uri = URI(" + rubyStr(effectiveURL(s)) + ")\n\n")
	b.WriteString("http = Net::HTTP.new(uri.host, uri.port)\n")
	b.WriteString("http.use_ssl = (uri.scheme == 'https')\n")
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("http.open_timeout = %d\nhttp.read_timeout = %d\n", s.Timeout, s.Timeout))
	}
	if s.Body != "" {
		b.WriteString("body = " + rubyStr(s.Body) + "\n")
	} else if len(s.Form) > 0 {
		b.WriteString("body = URI.encode_www_form({\n")
		for _, f := range s.Form {
			b.WriteString("  " + rubyStr(f.Name) + " => " + rubyStr(f.Value) + ",\n")
		}
		b.WriteString("})\n")
	}
	cls := "Net::HTTP::" + capWords(s.Method)
	if s.Body != "" || len(s.Form) > 0 {
		b.WriteString("request = " + cls + ".new(uri)\n")
		b.WriteString("request.body = body\n")
	} else {
		b.WriteString("request = " + cls + ".new(uri)\n")
	}
	for _, h := range s.Headers {
		b.WriteString("request[" + rubyStr(h.Name) + "] = " + rubyStr(h.Value) + "\n")
	}
	b.WriteString("response = http.request(request)\n")
	b.WriteString("puts response.code\n")
	b.WriteString("puts response.body\n")
	return b.String()
}

func capWords(m string) string {
	parts := strings.Split(strings.ToLower(m), "-")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

