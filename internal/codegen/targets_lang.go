func genRust(s *Snippet) string {
	var b strings.Builder
	b.WriteString("// Code generated by rAPI. Requires reqwest and tokio (features = [\"full\"])\n")
	b.WriteString(rustComment(s))
	b.WriteString("use std::collections::HashMap;\n\n")
	b.WriteString("#[tokio::main]\n")
	b.WriteString("async fn main() -> Result<(), reqwest::Error> {\n")
	b.WriteString("    let client = reqwest::Client::new();\n")
	if s.Body != "" {
		b.WriteString("    let body = " + rustStr(s.Body) + ";\n")
	}
	if len(s.Form) > 0 {
		b.WriteString("    let mut form = HashMap::new();\n")
		for _, f := range s.Form {
			b.WriteString("    form.insert(" + rustStr(f.Name) + ", " + rustStr(f.Value) + ");\n")
		}
	}
	b.WriteString("    let res = client\n")
	b.WriteString("        ." + strings.ToLower(s.Method) + "(" + rustStr(effectiveURL(s)) + ")\n")
	for _, h := range s.Headers {
		b.WriteString("        .header(" + rustStr(h.Name) + ", " + rustStr(h.Value) + ")\n")
	}
	if s.Body != "" {
		b.WriteString("        .body(body)\n")
	} else if len(s.Form) > 0 {
		b.WriteString("        .form(&form)\n")
	}
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("        .timeout(std::time::Duration::from_secs(%d))\n", s.Timeout))
	}
	b.WriteString("        .send()\n")
	b.WriteString("        .await?;\n")
	b.WriteString("    println!(\"{}\", res.status());\n")
	b.WriteString("    println!(\"{}\", res.text().await?);\n")
	b.WriteString("    Ok(())\n")
	b.WriteString("}\n")
	return b.String()
}

