func genJava(s *Snippet) string {
	var b strings.Builder
	b.WriteString("// Code generated by rAPI. Requires com.squareup.okhttp3:okhttp\n")
	b.WriteString(javaComment(s))
	b.WriteString("import okhttp3.*;\n")
	if len(s.Form) > 0 {
		b.WriteString("import java.util.concurrent.TimeUnit;\n")
	}
	b.WriteString("\n")
	b.WriteString("public class Main {\n")
	b.WriteString("  public static void main(String[] args) throws Exception {\n")
	b.WriteString("    OkHttpClient client = new OkHttpClient();\n")
	if s.Body != "" {
		b.WriteString("    RequestBody body = RequestBody.create(" + javaStr(s.Body) + ", null);\n")
		b.WriteString("    Request request = new Request.Builder()\n")
	} else if len(s.Form) > 0 {
		b.WriteString("    FormBody.Builder fb = new FormBody.Builder();\n")
		for _, f := range s.Form {
			b.WriteString("    fb.add(" + javaStr(f.Name) + ", " + javaStr(f.Value) + ");\n")
		}
		b.WriteString("    RequestBody body = fb.build();\n")
		b.WriteString("    Request request = new Request.Builder()\n")
	} else {
		b.WriteString("    Request request = new Request.Builder()\n")
	}
	b.WriteString("      .url(" + javaStr(effectiveURL(s)) + ")\n")
	if s.Body != "" || len(s.Form) > 0 {
		b.WriteString("      .method(" + javaStr(s.Method) + ", body)\n")
	} else {
		b.WriteString("      .method(" + javaStr(s.Method) + ", null)\n")
	}
	for _, h := range s.Headers {
		b.WriteString("      .header(" + javaStr(h.Name) + ", " + javaStr(h.Value) + ")\n")
	}
	b.WriteString("      .build();\n")
	b.WriteString("    Response response = client.newCall(request).execute();\n")
	b.WriteString("    System.out.println(response.code());\n")
	b.WriteString("    System.out.println(response.body().string());\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

