// ---------- Go ----------

func goStr(v string) string {
	return `"` + strings.NewReplacer("\\", "\\\\", `"`, `\"`, "\n", "\\n").Replace(v) + `"`
}

func goComment(s *Snippet) string {
	var b strings.Builder
	for _, l := range strings.Split(strings.TrimRight(headerComment("// ", s), "\n"), "\n") {
		if l != "" {
			b.WriteString(l + "\n")
		}
	}
	return b.String()
}

func genGo(s *Snippet) string {
	var b strings.Builder
	b.WriteString("package main\n\n")
	b.WriteString("// Code generated by rAPI.\n")
	b.WriteString(goComment(s))
	b.WriteString("import (\n	\"fmt\"\n	\"io\"\n	\"net/http\"\n")
	if s.Timeout > 0 {
		b.WriteString("	\"time\"\n")
	}
	if s.Body != "" || len(s.Form) > 0 {
		b.WriteString("	\"strings\"\n")
	}
	b.WriteString(")\n\n")
	b.WriteString("func main() {\n")
	if s.Body != "" {
		b.WriteString("\tbody := " + goStr(s.Body) + "\n")
		b.WriteString("\treq, _ := http.NewRequest(" + goStr(s.Method) + ", " + goStr(effectiveURL(s)) + ", strings.NewReader(body))\n")
	} else if len(s.Form) > 0 {
		parts := make([]string, 0, len(s.Form))
		for _, f := range s.Form {
			parts = append(parts, f.Name+"="+f.Value)
		}
		b.WriteString("\tbody := " + goStr(strings.Join(parts, "&")) + "\n")
		b.WriteString("\treq, _ := http.NewRequest(" + goStr(s.Method) + ", " + goStr(effectiveURL(s)) + ", strings.NewReader(body))\n")
	} else {
		b.WriteString("\treq, _ := http.NewRequest(" + goStr(s.Method) + ", " + goStr(effectiveURL(s)) + ", nil)\n")
	}
	for _, h := range s.Headers {
		b.WriteString("\treq.Header.Set(" + goStr(h.Name) + ", " + goStr(h.Value) + ")\n")
	}
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("	client := &http.Client{Timeout: %d * time.Second}\n", s.Timeout))
	} else {
		b.WriteString("	client := &http.Client{}\n")
	}
	b.WriteString("\tres, err := client.Do(req)\n")
	b.WriteString("\tif err != nil {\n\t\tpanic(err)\n\t}\n")
	b.WriteString("\tdefer res.Body.Close()\n")
	b.WriteString("\tbodyText, _ := io.ReadAll(res.Body)\n")
	b.WriteString("\tfmt.Println(res.StatusCode, string(bodyText))\n")
	b.WriteString("}\n")
	return b.String()
}

