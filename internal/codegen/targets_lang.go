func genPHP(s *Snippet) string {
	var b strings.Builder
	b.WriteString("<?php\n// Code generated by rAPI.\n")
	b.WriteString(phpComment(s))
	b.WriteString("$ch = curl_init();\n")
	b.WriteString("curl_setopt($ch, CURLOPT_URL, " + phpStr(effectiveURL(s)) + ");\n")
	b.WriteString("curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);\n")
	b.WriteString("curl_setopt($ch, CURLOPT_CUSTOMREQUEST, " + phpStr(s.Method) + ");\n")
	headers := make([]string, 0, len(s.Headers)+1)
	for _, h := range s.Headers {
		headers = append(headers, h.Name+": "+h.Value)
	}
	if len(headers) > 0 {
		b.WriteString("curl_setopt($ch, CURLOPT_HTTPHEADER, [\n")
		for _, h := range headers {
			b.WriteString("  " + phpStr(h) + ",\n")
		}
		b.WriteString("]);\n")
	}
	if s.Body != "" {
		b.WriteString("curl_setopt($ch, CURLOPT_POSTFIELDS, " + phpStr(s.Body) + ");\n")
	} else if len(s.Form) > 0 {
		b.WriteString("curl_setopt($ch, CURLOPT_POSTFIELDS, http_build_query([\n")
		for _, f := range s.Form {
			b.WriteString("  " + phpStr(f.Name) + " => " + phpStr(f.Value) + ",\n")
		}
		b.WriteString("]));\n")
	} else if len(s.Multipart) > 0 {
		b.WriteString("curl_setopt($ch, CURLOPT_POSTFIELDS, [\n")
		for _, f := range s.Multipart {
			if strings.HasPrefix(f.Value, "@") {
				b.WriteString("  " + phpStr(f.Name) + " => new CURLFile(" + phpStr(strings.TrimPrefix(f.Value, "@")) + "),\n")
			} else {
				b.WriteString("  " + phpStr(f.Name) + " => " + phpStr(f.Value) + ",\n")
			}
		}
		b.WriteString("]);\n")
	}
	if s.Timeout > 0 {
		b.WriteString(fmt.Sprintf("curl_setopt($ch, CURLOPT_TIMEOUT, %d);\n", s.Timeout))
	}
	b.WriteString("$response = curl_exec($ch);\n")
	b.WriteString("$status = curl_getinfo($ch, CURLINFO_HTTP_CODE);\n")
	b.WriteString("curl_close($ch);\n")
	b.WriteString("echo $status, PHP_EOL, $response, PHP_EOL;\n")
	return b.String()
}

